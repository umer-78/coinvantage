// Writes js/deps.js: every module each page needs, so the browser can fetch
// them in parallel instead of discovering them one import level at a time
// (the coin page is six levels deep; on a phone each level is a round trip).
// Also writes the modulepreload links for the app shell into index.html.
// Re-run after changing imports: node tools/build-deps.mjs
// (tests/modules.test.mjs fails while the output is out of date).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const JS = join(ROOT, 'js');

const importsOf = (file) => [...readFileSync(file, 'utf8').matchAll(/^import\s[^;]*?from\s*['"](\.[^'"]+)['"]/gm)]
  .map((m) => resolve(dirname(file), m[1]));

function closure(file, acc = new Set()) {
  for (const dep of importsOf(file)) {
    if (acc.has(dep)) continue;
    acc.add(dep);
    closure(dep, acc);
  }
  return acc;
}

const rel = (f) => relative(JS, f).split('\\').join('/');
const list = (file) => [...closure(file)].map(rel).sort();

export function buildDeps() {
  const deps = { 'app.js': list(join(JS, 'app.js')) };
  for (const f of readdirSync(join(JS, 'views')).filter((x) => x.endsWith('.js')).sort()) {
    deps[`views/${f}`] = list(join(JS, 'views', f));
  }
  const js = `// Generated by tools/build-deps.mjs: do not edit by hand.
// Every module each page needs, so they can be fetched in parallel.
export const DEPS = ${JSON.stringify(deps, null, 2).replace(/"/g, "'")};
`;
  const links = ['app.js', ...deps['app.js']].map((f) => `  <link rel="modulepreload" href="js/${f}">`).join('\n');
  const html = readFileSync(join(ROOT, 'index.html'), 'utf8').replace(
    /<!-- modulepreload:start -->[\s\S]*?<!-- modulepreload:end -->/,
    `<!-- modulepreload:start -->\n${links}\n  <!-- modulepreload:end -->`,
  );
  return { js, html };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { js, html } = buildDeps();
  writeFileSync(join(JS, 'deps.js'), js);
  writeFileSync(join(ROOT, 'index.html'), html);
  console.log('js/deps.js and the index.html preload links are up to date');
}
